// Слова пользователя главнее плана (ADR 0021; правило — sreda:kak-rabotat, раздел 4).
//
// 29.10 пользователь сказал «за январь», а сессия загрузила один день 05.01 — шаг своего же плана пробы, который она
// дописала к его словам. Правило «своего не добавлять» было в навыке, но в момент запуска сессия на него не смотрела.
// Поэтому к каждому сообщению пользователя плагин добавляет для модели короткую пометку: новые слова главнее плана,
// свои шаги «моё» — убрать, перед запуском — сверка «слова → запускаю». Пометка идёт в context, текст не меняется.
// Пробуждения от сессий приходят с тем же origin «sdk», что и сообщения, — их отличаем по тексту (ADR 0016),
// как и отчёты субагентов.

const USER_ORIGINS = new Set(['composer', 'sdk', 'bridge'])
const NOT_USER = ['<side-sessions-event>', '[Subagent hand-back]']

export const SLOVA_NOTE =
  'sreda: это сообщение главнее твоего плана и прошлых проб. Свои шаги («моё»), которые его сужают или меняют, — ' +
  'убрать. Перед выгрузкой, загрузкой, прогоном — строка «ваши слова: «…» → запускаю: …»; не совпадает — окно.'

export function slovaPrompt(e: any): string | null {
  if (!USER_ORIGINS.has(e.origin?.kind) || e.command || e.isMeta) return null
  const text = String(e.text ?? '')
  return text.trim() && !NOT_USER.some(mark => text.includes(mark)) ? SLOVA_NOTE : null
}
